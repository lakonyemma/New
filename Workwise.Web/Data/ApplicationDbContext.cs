using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
using Workwise.Web.Models;
namespace Workwise.Web.Data;
public class ApplicationDbContext(DbContextOptions<ApplicationDbContext> options) : IdentityDbContext<ApplicationUser,IdentityRole<long>,long>(options) {
 public DbSet<Department> Departments => Set<Department>();
 public DbSet<Team> Teams => Set<Team>();
 public DbSet<EmployeeProfile> EmployeeProfiles => Set<EmployeeProfile>();
 public DbSet<Skill> Skills => Set<Skill>();
 public DbSet<EmployeeSkill> EmployeeSkills => Set<EmployeeSkill>();
 public DbSet<Project> Projects => Set<Project>();
 public DbSet<TaskItem> Tasks => Set<TaskItem>();
 public DbSet<TaskAssignment> TaskAssignments => Set<TaskAssignment>();
 public DbSet<TaskSkillRequirement> TaskSkillRequirements => Set<TaskSkillRequirement>();
 public DbSet<Notification> Notifications => Set<Notification>();
 public DbSet<TaskSubmission> TaskSubmissions => Set<TaskSubmission>();
 public DbSet<TaskReview> TaskReviews => Set<TaskReview>();
 public DbSet<SystemSetting> SystemSettings => Set<SystemSetting>();
 public DbSet<AuditLog> AuditLogs => Set<AuditLog>();
 public DbSet<TeamMember> TeamMembers => Set<TeamMember>();
 public DbSet<ProjectMember> ProjectMembers => Set<ProjectMember>();
 public DbSet<EmployeeAvailability> EmployeeAvailabilities => Set<EmployeeAvailability>();
 public DbSet<TaskDependency> TaskDependencies => Set<TaskDependency>();
 public DbSet<TaskComment> TaskComments => Set<TaskComment>();
 public DbSet<TaskAttachment> TaskAttachments => Set<TaskAttachment>();
 public DbSet<AllocationScore> AllocationScores => Set<AllocationScore>();
 public DbSet<AllocationHistory> AllocationHistories => Set<AllocationHistory>();
 public DbSet<AllocationRule> AllocationRules => Set<AllocationRule>();
 public DbSet<WorkloadRecord> WorkloadRecords => Set<WorkloadRecord>();
 public DbSet<TimeEntry> TimeEntries => Set<TimeEntry>();
 public DbSet<WorkSchedule> WorkSchedules => Set<WorkSchedule>();
 public DbSet<NotificationPreference> NotificationPreferences => Set<NotificationPreference>();
 protected override void OnModelCreating(ModelBuilder b) {
  base.OnModelCreating(b);
  b.Entity<EmployeeProfile>().HasKey(x=>x.UserId);
  b.Entity<EmployeeSkill>().HasKey(x=>new{x.EmployeeUserId,x.SkillId});
  b.Entity<TaskSkillRequirement>().HasKey(x=>new{x.TaskId,x.SkillId});
  b.Entity<TeamMember>().HasKey(x=>new{x.TeamId,x.EmployeeUserId});
  b.Entity<ProjectMember>().HasKey(x=>new{x.ProjectId,x.UserId});
  b.Entity<TaskDependency>().HasKey(x=>new{x.TaskId,x.DependsOnTaskId});
  b.Entity<NotificationPreference>().HasKey(x=>x.UserId);
  b.Entity<EmployeeProfile>().HasIndex(x=>x.EmployeeNumber).IsUnique();
  b.Entity<Department>().HasIndex(x=>x.Name).IsUnique();
  b.Entity<Skill>().HasIndex(x=>x.Name).IsUnique();
  b.Entity<SystemSetting>().HasIndex(x=>x.SettingKey).IsUnique();
  b.Entity<AllocationRule>().HasIndex(x=>x.Name).IsUnique();
  b.Entity<TaskAttachment>().HasIndex(x=>x.StorageKey).IsUnique();
  b.Entity<TaskItem>().HasIndex(x=>new{x.ProjectId,x.Status});
  b.Entity<TaskAssignment>().HasIndex(x=>new{x.TaskId,x.EmployeeUserId});
  b.Entity<TimeEntry>().HasIndex(x=>new{x.EmployeeUserId,x.StartedAt});
  b.Entity<Notification>().HasIndex(x=>new{x.RecipientUserId,x.ReadAt});
  b.Entity<Team>().HasOne<Department>().WithMany().HasForeignKey(x=>x.DepartmentId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<Team>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.SupervisorUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<EmployeeProfile>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.UserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<EmployeeProfile>().HasOne<Department>().WithMany().HasForeignKey(x=>x.DepartmentId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<EmployeeSkill>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.EmployeeUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<EmployeeSkill>().HasOne<Skill>().WithMany().HasForeignKey(x=>x.SkillId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<Project>().HasOne<Department>().WithMany().HasForeignKey(x=>x.DepartmentId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskItem>().HasOne<Project>().WithMany().HasForeignKey(x=>x.ProjectId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskItem>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.CreatedBy).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskAssignment>().HasOne<TaskItem>().WithMany().HasForeignKey(x=>x.TaskId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskAssignment>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.EmployeeUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskAssignment>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.AssignedBy).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskSkillRequirement>().HasOne<TaskItem>().WithMany().HasForeignKey(x=>x.TaskId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskSkillRequirement>().HasOne<Skill>().WithMany().HasForeignKey(x=>x.SkillId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<Notification>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.RecipientUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskSubmission>().HasOne<TaskItem>().WithMany().HasForeignKey(x=>x.TaskId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskSubmission>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.EmployeeUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskReview>().HasOne<TaskSubmission>().WithMany().HasForeignKey(x=>x.SubmissionId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskReview>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.ReviewerUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<SystemSetting>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.UpdatedBy).OnDelete(DeleteBehavior.Restrict);
  b.Entity<AuditLog>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.ActorUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TeamMember>().HasOne<Team>().WithMany().HasForeignKey(x=>x.TeamId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TeamMember>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.EmployeeUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<ProjectMember>().HasOne<Project>().WithMany().HasForeignKey(x=>x.ProjectId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<ProjectMember>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.UserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<EmployeeAvailability>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.EmployeeUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskDependency>().HasOne<TaskItem>().WithMany().HasForeignKey(x=>x.TaskId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskDependency>().HasOne<TaskItem>().WithMany().HasForeignKey(x=>x.DependsOnTaskId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskComment>().HasOne<TaskItem>().WithMany().HasForeignKey(x=>x.TaskId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskComment>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.AuthorUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskAttachment>().HasOne<TaskItem>().WithMany().HasForeignKey(x=>x.TaskId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TaskAttachment>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.UploadedBy).OnDelete(DeleteBehavior.Restrict);
  b.Entity<AllocationScore>().HasOne<TaskItem>().WithMany().HasForeignKey(x=>x.TaskId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<AllocationScore>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.EmployeeUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<AllocationHistory>().HasOne<TaskItem>().WithMany().HasForeignKey(x=>x.TaskId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<AllocationHistory>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.SuggestedEmployeeId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<AllocationHistory>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.SelectedEmployeeId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<AllocationHistory>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.DecisionBy).OnDelete(DeleteBehavior.Restrict);
  b.Entity<AllocationRule>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.UpdatedBy).OnDelete(DeleteBehavior.Restrict);
  b.Entity<WorkloadRecord>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.EmployeeUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TimeEntry>().HasOne<TaskItem>().WithMany().HasForeignKey(x=>x.TaskId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<TimeEntry>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.EmployeeUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<WorkSchedule>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.EmployeeUserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<NotificationPreference>().HasOne<ApplicationUser>().WithMany().HasForeignKey(x=>x.UserId).OnDelete(DeleteBehavior.Restrict);
  b.Entity<AllocationScore>().Property(x=>x.Score).HasPrecision(7,2);
  b.Entity<TaskSkillRequirement>().Property(x=>x.ImportanceWeight).HasPrecision(6,2);
 }
}
